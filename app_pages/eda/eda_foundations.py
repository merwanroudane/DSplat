st.markdown("## سير عمل EDA منظم")
STEPS = [
    ("Context", "ما السؤال؟ ما وحدة التحليل؟ كيف جُمعت البيانات؟ ما الذي لا تغطيه؟"),
    ("Structure", "الشكل، الأنواع، المفاتيح، الذاكرة. هل الأنواع تطابق المعنى؟"),
    ("Quality", "المفقود، التكرار، القيم المستحيلة، الاتساق — قبل أي تفسير."),
    ("Univariate", "توزيع كل متغير: المركز، التشتت، الشكل، القيم الطرفية."),
    ("Bivariate", "العلاقات مع الهدف ومع بعضها، حسب أنواع المتغيرات."),
    ("Multivariate", "التفاعلات، المتغيرات المربكة، التعدد الخطي، البنية العامة."),
    ("Segments & time", "هل تختلف الأنماط بين المجموعات أو عبر الزمن؟"),
    ("Hypotheses", "صياغة فرضيات قابلة للاختبار — لا اختبارها على نفس البيانات."),
    ("Document", "سجل الملاحظات والقرارات والأسئلة المفتوحة."),
]


def _render(i: int) -> None:
    flow([s[0] for s in STEPS], highlight=i)
    st.markdown(f"**{i + 1}. {STEPS[i][0]}** — {STEPS[i][1]}")


stepper("eda_flow", len(STEPS), _render, labels=[s[0] for s in STEPS])

st.markdown("## أسئلة EDA المفيدة")
st.markdown(
    "- ما شكل توزيع الهدف؟ هل هو متوازن؟\n- أي المتغيرات أكثر ارتباطًا بالهدف؟ هل العلاقة خطية؟\n"
    "- هل هناك مجموعات فرعية بسلوك مختلف؟\n- هل تتغير العلاقات عبر الزمن؟\n"
    "- ما الذي يبدو «جيدًا جدًا ليكون صحيحًا»؟ (غالبًا Leakage أو خطأ)"
)
why("افصل بين الاستكشاف والتأكيد: خصص جزءًا من البيانات أو فترة زمنية لاحقة لاختبار الفرضيات.",
    "مع كفاية المحاولات ستجد دائمًا نمطًا «دالًا» بالصدفة. ما تكتشفه في EDA فرضية، لا نتيجة.")

