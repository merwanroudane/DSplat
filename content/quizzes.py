def _skew_chart() -> go.Figure:
    rng = np.random.default_rng(3)
    x = rng.lognormal(3, 0.7, 800)
    fig = go.Figure(go.Histogram(x=x, nbinsx=50, marker_color="#F76707"))
    fig.add_vline(x=float(np.mean(x)), line_color="#7048E8", annotation_text="A")
    fig.add_vline(x=float(np.median(x)), line_color="#0B7285", annotation_text="B")
    fig.update_layout(height=260, margin=dict(t=20, b=30), showlegend=False)
    return fig


def _truncated_chart() -> go.Figure:
    fig = go.Figure(go.Bar(x=["2023", "2024"], y=[102, 104], marker_color=["#74C0FC", "#F76707"]))
    fig.update_layout(height=260, yaxis=dict(range=[101, 104.5]), margin=dict(t=20, b=30))
    return fig


def _roc_chart() -> go.Figure:
    t = np.linspace(0, 1, 50)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=t, y=t ** 0.25, name="Model A", line=dict(color="#F76707")))
    fig.add_trace(go.Scatter(x=t, y=t ** 0.6, name="Model B", line=dict(color="#7048E8")))
    fig.add_trace(go.Scatter(x=[0, 1], y=[0, 1], name="Random", line=dict(dash="dash", color="#999")))
    fig.update_layout(height=280, xaxis_title="FPR", yaxis_title="TPR", margin=dict(t=20, b=30))
    return fig


def _elbow_chart() -> go.Figure:
    k = np.arange(1, 10)
    inertia = [1000, 520, 260, 230, 210, 195, 185, 178, 172]
    fig = go.Figure(go.Scatter(x=k, y=inertia, mode="lines+markers", line=dict(color="#F76707")))
    fig.update_layout(height=260, xaxis_title="k", yaxis_title="Inertia", margin=dict(t=20, b=30))
    return fig


